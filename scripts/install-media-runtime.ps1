[CmdletBinding()]
param([string]$From = '')

# Optional, user-invoked installer. No administrator access or system tool install.
# Only the pinned upstream executable and its notices enter this portable folder.
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$workRoot = $null
$resourcesRoot = $null

function Assert-ChildPath([string]$Parent, [string]$Child) {
    $parentPath = [IO.Path]::GetFullPath($Parent).TrimEnd([IO.Path]::DirectorySeparatorChar) + [IO.Path]::DirectorySeparatorChar
    $childPath = [IO.Path]::GetFullPath($Child)
    if (-not $childPath.StartsWith($parentPath, [StringComparison]::OrdinalIgnoreCase)) {
        throw 'A media runtime path escapes the portable application folder.'
    }
}

function Assert-PlainPath([string]$Path) {
    $currentPath = [IO.Path]::GetFullPath($Path)
    while ($currentPath) {
        if (Test-Path -LiteralPath $currentPath) {
            $item = Get-Item -LiteralPath $currentPath -Force
            if ($item.Attributes -band [IO.FileAttributes]::ReparsePoint) {
                throw 'Linked or redirected paths are not supported by this installer.'
            }
        }
        $parentPath = [IO.Path]::GetDirectoryName($currentPath)
        if ($parentPath -eq $currentPath) { break }
        $currentPath = $parentPath
    }
}

function Assert-PlainTree([string]$Path) {
    Assert-PlainPath $Path
    foreach ($item in Get-ChildItem -LiteralPath $Path -Force) {
        if ($item.Attributes -band [IO.FileAttributes]::ReparsePoint) { throw 'A temporary folder contains a link; it has been preserved.' }
        if ($item.PSIsContainer) { Assert-PlainTree $item.FullName }
    }
}

function Assert-Hash([string]$Path, [string]$Expected) {
    Assert-PlainPath $Path
    if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) { throw ('Required file is missing: ' + [IO.Path]::GetFileName($Path)) }
    if ($Expected -notmatch '^[a-fA-F0-9]{64}$') { throw 'The pinned media manifest has an invalid SHA-256 value.' }
    if ((Get-Sha256 $Path) -ne $Expected) {
        throw ('SHA-256 mismatch: ' + [IO.Path]::GetFileName($Path) + '. No existing runtime has been changed.')
    }
}

function Get-Sha256([string]$Path) {
    $algorithm = [Security.Cryptography.SHA256]::Create()
    $stream = [IO.File]::OpenRead($Path)
    try { return ([BitConverter]::ToString($algorithm.ComputeHash($stream))).Replace('-', '').ToLowerInvariant() }
    finally { $stream.Dispose(); $algorithm.Dispose() }
}

function Assert-Runtime([string]$Directory, $Manifest) {
    Assert-PlainPath $Directory
    foreach ($name in @('ffmpeg.exe', 'COPYING.GPLv3.txt', 'UPSTREAM-README.txt', 'SOURCES.md')) {
        Assert-Hash (Join-Path $Directory $name) $Manifest.sha256.$name
    }
    Assert-Hash (Join-Path $Directory 'runtime.json') (Get-Sha256 (Join-Path $PSScriptRoot 'runtime.json'))
}

function Find-SevenZip {
    foreach ($name in @('7z.exe', '7za.exe')) {
        $command = Get-Command -Name $name -CommandType Application -ErrorAction SilentlyContinue | Select-Object -First 1
        if ($command) { return $command.Source }
    }
    foreach ($basePath in @($env:ProgramFiles, ${env:ProgramFiles(x86)})) {
        if ($basePath) {
            $candidate = Join-Path $basePath '7-Zip\7z.exe'
            if (Test-Path -LiteralPath $candidate -PathType Leaf) { return $candidate }
        }
    }
    return $null
}

try {
    $setupRoot = [IO.Path]::GetFullPath($PSScriptRoot)
    $resourcesRoot = [IO.Path]::GetDirectoryName($setupRoot)
    $packageRoot = [IO.Path]::GetDirectoryName($resourcesRoot)
    if ([IO.Path]::GetFileName($setupRoot) -ne 'media-runtime-setup' -or [IO.Path]::GetFileName($resourcesRoot) -ne 'resources') {
        throw 'Run this installer from the extracted UFriend portable package, using Install media runtime.cmd.'
    }
    Assert-PlainPath $setupRoot
    $buildFile = Join-Path $packageRoot 'BUILD-INFO.json'
    $markerFile = Join-Path $packageRoot '.ufriend-package-output'
    if (-not (Test-Path -LiteralPath $buildFile -PathType Leaf) -or -not (Test-Path -LiteralPath $markerFile -PathType Leaf)) {
        throw 'The UFriend portable package marker or build information is missing.'
    }
    Assert-PlainPath $buildFile
    Assert-PlainPath $markerFile
    $build = Get-Content -LiteralPath $buildFile -Raw | ConvertFrom-Json
    if ($build.product -ne 'UFriend' -or $build.version -notmatch '^\d+\.\d+\.\d+$') { throw 'This is not a recognized UFriend portable package.' }
    if ((Get-Content -LiteralPath $markerFile -Raw) -ne "Generated by scripts/package.cjs`n") { throw 'The portable package marker is invalid.' }
    $manifestFile = Join-Path $setupRoot 'runtime.json'
    Assert-PlainPath $manifestFile
    $runtime = Get-Content -LiteralPath $manifestFile -Raw | ConvertFrom-Json
    if ($runtime.product -ne 'FFmpeg' -or $runtime.platform -ne 'win32' -or $runtime.architecture -ne 'x64' -or $runtime.license -ne 'GPL-3.0') {
        throw 'The pinned media runtime manifest is not supported.'
    }
    if ($runtime.archive.url -ne 'https://www.gyan.dev/ffmpeg/builds/packages/ffmpeg-8.1.2-essentials_build.7z' -or $runtime.archive.sha256 -notmatch '^[a-fA-F0-9]{64}$') {
        throw 'The pinned upstream archive must use the expected Gyan HTTPS URL and SHA-256.'
    }
    if ($runtime.version -ne $build.videoRuntime.expectedVersion -or $runtime.sha256.'ffmpeg.exe' -ne $build.videoRuntime.expectedSha256) {
        throw 'The installer manifest does not match this package build.'
    }
    foreach ($name in @('COPYING.GPLv3.txt', 'UPSTREAM-README.txt', 'SOURCES.md')) {
        Assert-Hash (Join-Path $setupRoot $name) $runtime.sha256.$name
    }
    $destination = Join-Path $resourcesRoot 'ffmpeg'
    Assert-ChildPath $resourcesRoot $destination
    Assert-PlainPath $destination
    if (Test-Path -LiteralPath $destination) {
        Assert-Runtime $destination $runtime
        Write-Host 'The verified media runtime is already installed. No files were changed.'
        exit 0
    }

    $sevenZip = $null
    if (-not $From) {
        $sevenZip = Find-SevenZip
        if (-not $sevenZip) {
            Write-Host '7-Zip was not found. No download or system installation was started.'
            Write-Host ('Download the official archive: ' + $runtime.archive.url)
            Write-Host ('Expected archive SHA-256: ' + $runtime.archive.sha256)
            Write-Host 'Verify with: Get-FileHash -Algorithm SHA256 -LiteralPath <downloaded archive>'
            Write-Host 'Extract the archive with your own 7-Zip-compatible tool. Then run:'
            Write-Host '  "Install media runtime.cmd" -From "C:\path\ffmpeg-8.1.2-essentials_build"'
            throw '7-Zip is required for automatic extraction; use -From with an already extracted upstream package.'
        }
    }

    $workRoot = Join-Path $resourcesRoot ('.media-runtime-install-' + [Guid]::NewGuid().ToString('N'))
    Assert-ChildPath $resourcesRoot $workRoot
    Assert-PlainPath $workRoot
    if (Test-Path -LiteralPath $workRoot) { throw 'The temporary installation directory already exists.' }
    [void][IO.Directory]::CreateDirectory($workRoot)
    if ($From) {
        $sourceRoot = [IO.Path]::GetFullPath($From)
        Assert-PlainPath $sourceRoot
        if (-not (Test-Path -LiteralPath $sourceRoot -PathType Container)) { throw '-From must be an extracted upstream package directory.' }
    } else {
        $archive = Join-Path $workRoot 'ffmpeg.7z'
        Write-Host ('Downloading the optional media runtime directly from ' + $runtime.publisher + '...')
        [Net.ServicePointManager]::SecurityProtocol = [Net.ServicePointManager]::SecurityProtocol -bor [Net.SecurityProtocolType]::Tls12
        Invoke-WebRequest -Uri $runtime.archive.url -OutFile $archive -UseBasicParsing
        Assert-Hash $archive $runtime.archive.sha256
        $sourceRoot = Join-Path $workRoot 'upstream'
        [void][IO.Directory]::CreateDirectory($sourceRoot)
        & $sevenZip 'x' '-y' ('-o' + $sourceRoot) '--' $archive | Out-Null
        if ($LASTEXITCODE -ne 0) { throw '7-Zip could not extract the verified archive.' }
        Assert-PlainTree $sourceRoot
    }
    if (-not (Test-Path -LiteralPath (Join-Path $sourceRoot 'bin\ffmpeg.exe') -PathType Leaf)) {
        $candidates = @(Get-ChildItem -LiteralPath $sourceRoot -Directory -Force | Where-Object { Test-Path -LiteralPath (Join-Path $_.FullName 'bin\ffmpeg.exe') -PathType Leaf })
        if ($candidates.Count -ne 1) { throw 'Choose the upstream directory containing bin\ffmpeg.exe, LICENSE, and README.txt.' }
        $sourceRoot = $candidates[0].FullName
        Assert-PlainPath $sourceRoot
    }
    $inputs = @{
        'ffmpeg.exe' = Join-Path $sourceRoot 'bin\ffmpeg.exe'
        'COPYING.GPLv3.txt' = Join-Path $sourceRoot 'LICENSE'
        'UPSTREAM-README.txt' = Join-Path $sourceRoot 'README.txt'
        'SOURCES.md' = Join-Path $setupRoot 'SOURCES.md'
    }
    # Verify every upstream file before publishing the installation directory.
    foreach ($name in $inputs.Keys) { Assert-Hash $inputs[$name] $runtime.sha256.$name }
    $staging = Join-Path $workRoot 'verified-runtime'
    [void][IO.Directory]::CreateDirectory($staging)
    foreach ($name in $inputs.Keys) { [IO.File]::Copy($inputs[$name], (Join-Path $staging $name), $false) }
    [IO.File]::Copy($manifestFile, (Join-Path $staging 'runtime.json'), $false)
    Assert-Runtime $staging $runtime
    Assert-ChildPath $resourcesRoot $staging
    Assert-ChildPath $resourcesRoot $destination
    Assert-PlainPath $staging
    Assert-PlainPath $destination
    # Atomic directory publication; a concurrent or existing install is preserved.
    [IO.Directory]::Move($staging, $destination)
    Write-Host 'Verified media runtime installed. Captioned-video export is now available in UFriend.'
    Write-Host 'The upstream GPL license, README, and source information are preserved in resources\ffmpeg.'
} catch {
    Write-Error -Message $_.Exception.Message -ErrorAction Continue
    exit 1
} finally {
    if ($workRoot -and (Test-Path -LiteralPath $workRoot)) {
        try {
            Assert-ChildPath $resourcesRoot $workRoot
            Assert-PlainTree $workRoot
            Remove-Item -LiteralPath $workRoot -Recurse -Force
        } catch {
            Write-Warning ('The temporary directory was preserved: ' + $workRoot)
        }
    }
}
