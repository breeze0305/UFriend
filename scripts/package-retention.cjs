'use strict';

const fs=require('node:fs'),path=require('node:path');
const {spawnSync}=require('node:child_process');
const marker='.ufriend-package-output',markerText='Generated by scripts/package.cjs\n';
const versionPattern=/^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/;
const folderPattern=/^UFriend-(\d+\.\d+\.\d+)(?:-build-\d{8}-\d{6}-\d{3})?$/;
const samePath=(a,b)=>process.platform==='win32'?a.toLowerCase()===b.toLowerCase():a===b;
const inside=(root,file)=>{const relative=path.relative(root,file);return!!relative&&!relative.startsWith('..'+path.sep)&&relative!=='..'&&!path.isAbsolute(relative);};

function checkedRoot(directory){
  const root=path.resolve(directory);
  const parent=path.dirname(root);
  if(root===parent||!samePath(fs.realpathSync(parent),parent))throw new Error('成品目錄的解析路徑不安全，未執行清理。');
  if(fs.existsSync(root)&&(!fs.lstatSync(root).isDirectory()||fs.lstatSync(root).isSymbolicLink()||!samePath(fs.realpathSync(root),root)))throw new Error('成品目錄不可使用連結，未執行清理。');
  return root;
}
function realFile(root,file){
  if(!inside(root,file)||!fs.lstatSync(file).isFile()||!samePath(fs.realpathSync(file),file))throw new Error('成品檔案位置或類型不符。');
  return file;
}
function inspectPackage(root,name){
  const match=folderPattern.exec(name);if(name!=='UFriend'&&!match)return null;
  const directory=path.resolve(root,name);
  if(!samePath(path.dirname(directory),root)||!fs.lstatSync(directory).isDirectory()||fs.lstatSync(directory).isSymbolicLink()||!samePath(fs.realpathSync(directory),directory))return null;
  if(fs.readFileSync(realFile(directory,path.join(directory,marker)),'utf8')!==markerText)return null;
  const manifest=JSON.parse(fs.readFileSync(realFile(directory,path.join(directory,'resources','app','package.json')),'utf8'));
  const build=JSON.parse(fs.readFileSync(realFile(directory,path.join(directory,'BUILD-INFO.json')),'utf8'));
  if(manifest.name!=='ufriend'||typeof manifest.version!=='string'||manifest.version.length>32||!versionPattern.test(manifest.version)||match&&match[1]!==manifest.version||build.product!=='UFriend'||build.version!==manifest.version||typeof build.builtAt!=='string'||!Number.isFinite(Date.parse(build.builtAt)))return null;
  if(!fs.statSync(realFile(directory,path.join(directory,'UFriend.exe'))).size)return null;
  realFile(directory,path.join(directory,'resources','app','app','main.cjs'));
  return{name,path:directory,version:manifest.version,builtAt:build.builtAt};
}
function inspectPackages(directory){
  const root=checkedRoot(directory),packages=[],ignored=[];
  if(!fs.existsSync(root))return{packages,ignored};
  for(const entry of fs.readdirSync(root)){if(entry==='.ufriend-package.lock')continue;let item;try{item=inspectPackage(root,entry);}catch{}if(item)packages.push(item);else ignored.push(entry);}
  return{packages,ignored};
}
function compareVersions(left,right){
  const a=left.split('.').map(BigInt),b=right.split('.').map(BigInt);
  for(let i=0;i<3;i++)if(a[i]!==b[i])return a[i]>b[i]?1:-1;
  return 0;
}
function latestPackage(packages){return[...packages].sort((a,b)=>compareVersions(b.version,a.version)||Date.parse(b.builtAt)-Date.parse(a.builtAt)||b.name.localeCompare(a.name))[0]||null;}
function checkTree(root,directory){
  if(!samePath(root,directory)&&!inside(root,directory))throw new Error('目標超出成品資料夾。');
  if(fs.lstatSync(directory).isSymbolicLink()||!samePath(fs.realpathSync(directory),directory))throw new Error('成品含有連結，已保留。');
  let bytes=0;
  for(const entry of fs.readdirSync(directory,{withFileTypes:true})){
    const file=path.join(directory,entry.name);
    if(entry.isSymbolicLink())throw new Error('成品含有連結，已保留。');
    if(entry.isDirectory())bytes+=checkTree(root,file);
    else{realFile(root,file);bytes+=fs.statSync(file).size;}
  }
  return bytes;
}
function runningPaths(root){
  if(process.platform!=='win32')throw new Error('無法確認 Windows 程序。');
  const command="$ErrorActionPreference='Stop'; [Console]::OutputEncoding=[System.Text.UTF8Encoding]::new($false); $taskRoot=[IO.Path]::GetFullPath($env:UFRIEND_PACKAGE_DIST_ROOT).TrimEnd([IO.Path]::DirectorySeparatorChar)+[IO.Path]::DirectorySeparatorChar; $taskItems=@(Get-CimInstance Win32_Process | Where-Object { ($_.ExecutablePath -and $_.ExecutablePath.StartsWith($taskRoot,[StringComparison]::OrdinalIgnoreCase)) -or $_.Name -in @('UFriend.exe','ClipboardListener.exe') } | Select-Object Name,ExecutablePath); ConvertTo-Json -InputObject $taskItems -Compress";
  const result=spawnSync('powershell.exe',['-NoProfile','-NonInteractive','-Command',command],{encoding:'utf8',windowsHide:true,timeout:15000,env:{...process.env,UFRIEND_PACKAGE_DIST_ROOT:root}});
  if(result.error||result.status!==0)throw new Error('無法確認執行中的程式。');
  const records=JSON.parse(result.stdout.trim()||'[]');if(!Array.isArray(records))throw new Error('程序查詢格式錯誤。');
  return records.map(record=>record.ExecutablePath||null);
}
function prunePackages(directory,{getRunningPaths=runningPaths,remove=fs.rmSync}={}){
  const root=checkedRoot(directory),{packages,ignored}=inspectPackages(root),keep=latestPackage(packages),removed=[],skipped=[];
  const report={keep,removed,skipped,ignored,removedBytes:0};if(!keep)return report;
  // Validate the retained complete package before removing any other package.
  checkTree(keep.path,keep.path);
  const candidates=packages.filter(item=>!samePath(item.path,keep.path));if(!candidates.length)return report;
  for(const item of candidates){
    try{
      const current=inspectPackage(checkedRoot(root),item.name);
      if(!current||!samePath(current.path,item.path)||current.version!==item.version||current.builtAt!==item.builtAt||samePath(current.path,keep.path))throw new Error('成品在清理前已變動，已保留。');
      const bytes=checkTree(item.path,item.path);
      // Refresh after scanning each candidate so earlier deletions cannot leave
      // a stale process snapshot for a version started while cleanup was running.
      let processes;
      try{processes=getRunningPaths(root);if(!Array.isArray(processes)||processes.some(file=>typeof file!=='string'||!path.isAbsolute(file)))throw new Error('程序路徑不完整。');}
      catch{skipped.push({name:item.name,reason:'無法確認執行中的程式，請關閉舊版後再清理。'});continue;}
      if(processes.some(file=>inside(item.path,path.resolve(file)))){skipped.push({name:item.name,reason:'此版本仍在執行，請從系統匣結束後再清理。'});continue;}
      // The absolute target and all descendants were checked against this dist child.
      remove(item.path,{recursive:true,force:false,maxRetries:2,retryDelay:100});removed.push(item.name);report.removedBytes+=bytes;
    }catch{skipped.push({name:item.name,reason:'成品含有連結、已變動或檔案鎖定，未能清理；請關閉舊版後重試。'});}
  }
  return report;
}
function withDistLock(directory,work){
  const root=checkedRoot(directory);fs.mkdirSync(root,{recursive:true});checkedRoot(root);
  const lock=path.join(root,'.ufriend-package.lock');let fd;
  try{fd=fs.openSync(lock,'wx');}catch(error){if(error.code==='EEXIST')throw new Error('另一次打包或清理尚未結束；若先前異常中斷，請確認程序已結束後移除 dist/.ufriend-package.lock。');throw error;}
  try{fs.writeFileSync(fd,String(process.pid));return work();}finally{fs.closeSync(fd);fs.unlinkSync(lock);}
}
function printReport(report){
  console.log(report.keep?'保留最新成品：'+report.keep.name:'沒有找到可確認的完整 UFriend 成品，未刪除任何資料。');
  for(const name of report.removed)console.log('已清理：'+name);
  for(const item of report.skipped)console.warn('暫時保留 '+item.name+'：'+item.reason);
  for(const name of report.ignored)console.log('保留未識別項目：'+name);
  if(report.skipped.length)console.log('正常結束舊版後，可執行 npm run clean:dist 再次清理。');
}
module.exports={inspectPackages,latestPackage,compareVersions,prunePackages,withDistLock,printReport};
if(require.main===module){try{const report=withDistLock(path.resolve(__dirname,'../dist'),()=>prunePackages(path.resolve(__dirname,'../dist')));printReport(report);if(report.skipped.length)process.exitCode=1;}catch(error){console.error('清理未完成：'+error.message);process.exitCode=1;}}
