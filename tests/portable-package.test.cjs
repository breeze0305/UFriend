'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { portableOptions, inspectTree, assertPortableExecutable, buildPortable } = require('../scripts/package-portable.cjs');
const config = require('../scripts/electron-builder-portable.json');
const { getPinnedRuntime } = require('../scripts/ffmpeg-runtime.cjs');

const projectRoot = path.resolve(__dirname, '..');
const windows = { skip: process.platform !== 'win32' || process.arch !== 'x64' };
const version = require('../package.json').version;
const artifactName = `UFriend-${version}.exe`;

function fixture(t) {
  const parent = path.join(projectRoot, '.test-data', 'portable-package');
  fs.mkdirSync(parent, { recursive: true });
  assert.equal(fs.realpathSync(parent).toLowerCase(), parent.toLowerCase());
  const root = fs.mkdtempSync(path.join(parent, 'case-'));
  const input = path.join(root, 'dist', `UFriend-${version}`);
  const runtime = path.join(input, 'resources', 'app');
  fs.mkdirSync(path.join(runtime, 'app', 'config'), { recursive: true });
  fs.mkdirSync(path.join(root, 'node_modules', 'electron-builder'), { recursive: true });
  fs.mkdirSync(path.join(root, 'scripts'));
  const manifest = { name: 'ufriend', version, devDependencies: { 'electron-builder': '26.17.0' } };
  fs.writeFileSync(path.join(root, 'package.json'), JSON.stringify(manifest));
  fs.writeFileSync(path.join(root, 'node_modules', 'electron-builder', 'package.json'), JSON.stringify({ version: '26.17.0' }));
  fs.writeFileSync(path.join(root, 'node_modules', 'electron-builder', 'cli.js'), '// Fixture only; never executed.');
  fs.writeFileSync(path.join(root, 'scripts', 'electron-builder-portable.json'), JSON.stringify(config));
  fs.writeFileSync(path.join(input, '.ufriend-package-output'), 'Generated by scripts/package.cjs\n');
  fs.writeFileSync(path.join(input, 'UFriend.exe'), 'Synthetic application; never executed.');
  fs.writeFileSync(path.join(runtime, 'package.json'), JSON.stringify({ name: 'ufriend', version }));
  fs.writeFileSync(path.join(runtime, 'app', 'main.cjs'), '// Synthetic application; never executed.');
  fs.writeFileSync(path.join(runtime, 'app', 'config', 'google-oauth.json'), JSON.stringify({ clientId: '', clientSecret: '' }));
  const build = { product: 'UFriend', version, builtAt: '2026-10-11T00:00:00Z', platform: 'win32', architecture: 'x64', electron: '44.3.0', signed: false, gmailConfigured: false, videoRuntime: { bundled: false } };
  fs.writeFileSync(path.join(input, 'BUILD-INFO.json'), JSON.stringify(build));
  for (const name of ['LICENSE', 'LICENSES.chromium.html', 'LICENSE.UFriend.txt', 'THIRD_PARTY_NOTICES.md']) fs.writeFileSync(path.join(input, name), 'Synthetic notice: ' + name);
  const oldRelease = path.join(root, 'local', 'releases', 'previous-successful-release');
  fs.mkdirSync(oldRelease, { recursive: true });
  fs.writeFileSync(path.join(oldRelease, 'keep.exe'), 'Existing release must survive.');
  const links = [];
  t.after(() => {
    assert.equal(path.dirname(root), parent);
    assert.equal(fs.realpathSync(root).toLowerCase(), root.toLowerCase());
    for (const link of links) {
      assert.equal(path.relative(root, link).startsWith('..'), false);
      fs.unlinkSync(link);
    }
    fs.rmSync(root, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 });
  });
  return { root, input, runtime, oldRelease, build, links };
}

function outputFromArgs(args) {
  const option = args.find(arg => arg.startsWith('--config.directories.output='));
  assert(option);
  return option.slice('--config.directories.output='.length);
}

function syntheticPortable(directory, name = artifactName) {
  const bytes = Buffer.alloc(2048);
  bytes.write('MZ');
  bytes.writeUInt32LE(128, 0x3c);
  Buffer.from([0x50, 0x45, 0, 0]).copy(bytes, 128);
  fs.writeFileSync(path.join(directory, name), bytes);
}

function bundledFixture(t) {
  const pinnedRuntime = getPinnedRuntime();
  const f = fixture(t), directory = path.join(f.input, 'resources', 'ffmpeg');
  fs.mkdirSync(directory);
  for (const name of Object.keys(pinnedRuntime.sha256)) fs.writeFileSync(path.join(directory, name), 'Synthetic pinned runtime fixture: ' + name);
  fs.writeFileSync(path.join(directory, 'runtime.json'), JSON.stringify(pinnedRuntime));
  const verified = { executable: path.join(directory, 'ffmpeg.exe'), version: pinnedRuntime.version, sha256: pinnedRuntime.sha256['ffmpeg.exe'], license: pinnedRuntime.license, sourceRevision: pinnedRuntime.sourceRevision, sourceArchive: pinnedRuntime.sourceArchive, filters: ['ass', 'subtitles'], encoders: ['libx264', 'aac', 'libmp3lame'] };
  const { executable, ...metadata } = verified;
  f.build.videoRuntime = { bundled: true, path: 'resources/ffmpeg/ffmpeg.exe', ...metadata };
  fs.writeFileSync(path.join(f.input, 'BUILD-INFO.json'), JSON.stringify(f.build));
  return { ...f, directory, verified, pinnedRuntime };
}

function noCleanupReport(root) {
  return { keep: { name: path.basename(root) }, removed: [], skipped: [], ignored: [] };
}

test('portable CLI requires explicit bundled mode and accepts it with either prepackaged argument order', () => {
  assert.deepEqual(portableOptions([]), {});
  const input = `dist/UFriend-${version}`;
  assert.deepEqual(portableOptions(['--prepackaged', input]), { prepackaged: path.resolve(input) });
  assert.deepEqual(portableOptions(['--with-ffmpeg']), { withFfmpeg: true });
  for (const args of [['--with-ffmpeg', '--prepackaged', input], ['--prepackaged', input, '--with-ffmpeg']]) assert.deepEqual(portableOptions(args), { withFfmpeg: true, prepackaged: path.resolve(input) });
  for (const args of [['--prepackaged'], ['--publish'], ['--prepackaged', '--publish'], ['--prepackaged', 'x', '--prepackaged', 'y'], ['--with-ffmpeg', '--with-ffmpeg'], ['--with-ffmpeg', 'yes']]) assert.throws(() => portableOptions(args), /Usage/);
});

