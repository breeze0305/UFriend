'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { portableOptions, inspectTree, assertPortableExecutable, buildPortable } = require('../scripts/package-portable.cjs');
const config = require('../scripts/electron-builder-portable.json');

const projectRoot = path.resolve(__dirname, '..');
const windows = { skip: process.platform !== 'win32' || process.arch !== 'x64' };
const version = '0.1.39';
const artifactName = `UFriend-${version}-Portable.exe`;

function fixture(t) {
  const parent = path.join(projectRoot, '.test-data', 'portable-package');
  fs.mkdirSync(parent, { recursive: true });
  assert.equal(fs.realpathSync(parent).toLowerCase(), parent.toLowerCase());
  const root = fs.mkdtempSync(path.join(parent, 'case-'));
  const input = path.join(root, 'dist', `UFriend-${version}`);
  const runtime = path.join(input, 'resources', 'app');
  fs.mkdirSync(path.join(runtime, 'app', 'config'), { recursive: true });
  fs.mkdirSync(path.join(root, 'node_modules', 'electron-builder'), { recursive: true });
  fs.mkdirSync(path.join(root, 'scripts'));
  const manifest = { name: 'ufriend', version, devDependencies: { 'electron-builder': '26.17.0' } };
  fs.writeFileSync(path.join(root, 'package.json'), JSON.stringify(manifest));
  fs.writeFileSync(path.join(root, 'node_modules', 'electron-builder', 'package.json'), JSON.stringify({ version: '26.17.0' }));
  fs.writeFileSync(path.join(root, 'node_modules', 'electron-builder', 'cli.js'), '// Fixture only; never executed.');
  fs.writeFileSync(path.join(root, 'scripts', 'electron-builder-portable.json'), JSON.stringify(config));
  fs.writeFileSync(path.join(input, '.ufriend-package-output'), 'Generated by scripts/package.cjs\n');
  fs.writeFileSync(path.join(input, 'UFriend.exe'), 'Synthetic application; never executed.');
  fs.writeFileSync(path.join(runtime, 'package.json'), JSON.stringify({ name: 'ufriend', version }));
  fs.writeFileSync(path.join(runtime, 'app', 'main.cjs'), '// Synthetic application; never executed.');
  fs.writeFileSync(path.join(runtime, 'app', 'config', 'google-oauth.json'), JSON.stringify({ clientId: '', clientSecret: '' }));
  const build = { product: 'UFriend', version, builtAt: '2026-10-11T00:00:00Z', platform: 'win32', architecture: 'x64', electron: '44.3.0', signed: false, gmailConfigured: false, videoRuntime: { bundled: false } };
  fs.writeFileSync(path.join(input, 'BUILD-INFO.json'), JSON.stringify(build));
  for (const name of ['LICENSE', 'LICENSES.chromium.html', 'LICENSE.UFriend.txt', 'THIRD_PARTY_NOTICES.md']) fs.writeFileSync(path.join(input, name), 'Synthetic notice: ' + name);
  const oldRelease = path.join(root, 'local', 'releases', 'previous-successful-release');
  fs.mkdirSync(oldRelease, { recursive: true });
  fs.writeFileSync(path.join(oldRelease, 'keep.exe'), 'Existing release must survive.');
  const links = [];
  t.after(() => {
    assert.equal(path.dirname(root), parent);
    assert.equal(fs.realpathSync(root).toLowerCase(), root.toLowerCase());
    for (const link of links) {
      assert.equal(path.relative(root, link).startsWith('..'), false);
      fs.unlinkSync(link);
    }
    fs.rmSync(root, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 });
  });
  return { root, input, runtime, oldRelease, build, links };
}

function outputFromArgs(args) {
  const option = args.find(arg => arg.startsWith('--config.directories.output='));
  assert(option);
  return option.slice('--config.directories.output='.length);
}

function syntheticPortable(directory) {
  const bytes = Buffer.alloc(2048);
  bytes.write('MZ');
  bytes.writeUInt32LE(128, 0x3c);
  Buffer.from([0x50, 0x45, 0, 0]).copy(bytes, 128);
  fs.writeFileSync(path.join(directory, artifactName), bytes);
}

function noCleanupReport(root) {
  return { keep: { name: path.basename(root) }, removed: [], skipped: [], ignored: [] };
}

test('portable CLI accepts only an optional explicit prepackaged folder', () => {
  assert.deepEqual(portableOptions([]), {});
  assert.deepEqual(portableOptions(['--prepackaged', 'dist/UFriend-0.1.39']), { prepackaged: path.resolve('dist/UFriend-0.1.39') });
  for (const args of [['--prepackaged'], ['--publish'], ['--prepackaged', '--publish'], ['--prepackaged', 'x', '--prepackaged', 'y']]) assert.throws(() => portableOptions(args), /Usage/);
});

test('portable configuration validates against the pinned builder schema', async () => {
  const { validateConfiguration } = require('app-builder-lib/out/util/config/config');
  await validateConfiguration(config);
  assert.equal(config.executableName, 'UFriend');
  assert.equal(config.win.signExecutable, false);
  assert.equal(config.publish, null);
  // 26.17.0 source maps true to per-launch $PLUGINSDIR; false reuses one build ID.
  assert.equal(config.portable.unpackDirName, true);
  assert.equal(config.portable.useZip, true);
});

test('successful wrapping preserves the verified input and prior release, then enables dist cleanup', windows, t => {
  const f = fixture(t);
  const before = inspectTree(f.input);
  let built = false, pruned = false;
  const result = buildPortable({ root: f.root, prepackaged: f.input,
    buildFolder: () => assert.fail('An explicit prepackaged folder must not be rebuilt.'),
    runBuilder: (command, args, options) => {
      assert.equal(command, process.execPath);
      assert.equal(args[args.indexOf('--prepackaged') + 1], f.input);
      assert.equal(args[args.indexOf('--publish') + 1], 'never');
      assert.equal(options.cwd, f.root);
      assert.equal(options.windowsHide, true);
      assert.equal(options.env.CSC_IDENTITY_AUTO_DISCOVERY, 'false');
      const output = outputFromArgs(args);
      assert.equal(path.dirname(output), path.join(f.root, 'local', 'releases'));
      assert.equal(output.startsWith(f.input + path.sep), false);
      assert.equal(fs.existsSync(path.join(output, 'PORTABLE-BUILD-INFO.json')), false);
      syntheticPortable(output); built = true;
      return { status: 0 };
    },
    prune: directory => {
      assert.equal(directory, path.join(f.root, 'dist'));
      assert.equal(built, true);
      const finished = fs.readdirSync(path.join(f.root, 'local', 'releases')).filter(name => name !== 'previous-successful-release');
      assert.equal(finished.length, 1);
      assert.equal(finished[0].startsWith('.'), false);
      assert(fs.existsSync(path.join(f.root, 'local', 'releases', finished[0], 'PORTABLE-BUILD-INFO.json')));
      pruned = true; return noCleanupReport(f.input);
    },
  });
  assert.equal(pruned, true);
  assert.equal(inspectTree(f.input).sha256, before.sha256);
  assert.equal(result.receipt.source.sha256, before.sha256);
  assert.equal(result.receipt.source.fileCount, before.fileCount);
  assert.equal(result.receipt.artifact.sha256, assertPortableExecutable(result.executable).sha256);
  assert.equal(result.receipt.unpackDirectory, 'unique-per-launch');
  assert.equal(fs.readFileSync(path.join(f.oldRelease, 'keep.exe'), 'utf8'), 'Existing release must survive.');
});

test('builder failure preserves earlier releases and leaves no completion receipt or cleanup', windows, t => {
  const f = fixture(t), before = inspectTree(f.input);
  let output;
  assert.throws(() => buildPortable({ root: f.root, prepackaged: f.input,
    runBuilder: (_command, args) => { output = outputFromArgs(args); syntheticPortable(output); return { status: 3 }; },
    prune: () => assert.fail('Failed builds cannot prune working packages.'),
  }), /existing releases were preserved/);
  assert.equal(fs.existsSync(path.join(output, 'PORTABLE-BUILD-INFO.json')), false);
  assert.equal(inspectTree(f.input).sha256, before.sha256);
  assert(fs.existsSync(path.join(f.oldRelease, 'keep.exe')));
});

test('an incomplete executable or changed input prevents completion and cleanup', windows, t => {
  for (const mode of ['invalid-executable', 'changed-input']) {
    const f = fixture(t);
    assert.throws(() => buildPortable({ root: f.root, prepackaged: f.input,
      runBuilder: (_command, args) => {
        const output = outputFromArgs(args);
        if (mode === 'invalid-executable') fs.writeFileSync(path.join(output, artifactName), 'Partial file');
        else { syntheticPortable(output); fs.writeFileSync(path.join(f.input, 'unexpected.txt'), 'Changed input'); }
        return { status: 0 };
      },
      prune: () => assert.fail('Invalid outputs cannot trigger cleanup.'),
    }), mode === 'invalid-executable' ? /empty or incomplete/ : /changed its verified input/);
    assert(fs.existsSync(path.join(f.oldRelease, 'keep.exe')));
  }
});

test('default packaging defers folder cleanup until the portable wrapper succeeds', windows, t => {
  const f = fixture(t);
  let folderCalls = 0;
  assert.throws(() => buildPortable({ root: f.root,
    buildFolder: options => { assert.deepEqual(options, { withoutFfmpeg: true, prune: false }); folderCalls++; return { outputRoot: f.input }; },
    runBuilder: () => ({ status: 1 }),
    prune: () => assert.fail('Wrapper failure must keep previous folder packages.'),
  }), /builder failed/);
  assert.equal(folderCalls, 1);
  assert(fs.existsSync(path.join(f.oldRelease, 'keep.exe')));
});

test('public input checks reject unverified output, credentials, FFmpeg and linked content before invoking builder', windows, t => {
  for (const mode of ['wrong-folder', 'oauth', 'ffmpeg', 'link', 'missing-notice']) {
    const f = fixture(t);
    let input = f.input;
    if (mode === 'wrong-folder') input = f.root;
    if (mode === 'oauth') fs.writeFileSync(path.join(f.runtime, 'app', 'config', 'google-oauth.json'), JSON.stringify({ clientId: 'synthetic-client' }));
    if (mode === 'ffmpeg') fs.writeFileSync(path.join(f.input, 'ffmpeg.exe'), 'Fixture only');
    if (mode === 'link') { const link = path.join(f.input, 'linked-content'); fs.symlinkSync(f.oldRelease, link, 'junction'); f.links.push(link); }
    if (mode === 'missing-notice') fs.unlinkSync(path.join(f.input, 'LICENSES.chromium.html'));
    assert.throws(() => buildPortable({ root: f.root, prepackaged: input,
      runBuilder: () => assert.fail('Invalid input must never reach the builder.'),
      prune: () => assert.fail('Invalid input must never prune releases.'),
    }));
    assert(fs.existsSync(path.join(f.oldRelease, 'keep.exe')));
  }
});
