'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { spawnSync } = require('node:child_process');
const { packagingOptions, copyMediaRuntimeSetup } = require('../scripts/package.cjs');
const { pinnedRuntime } = require('../scripts/ffmpeg-runtime.cjs');
const { inspectPackages } = require('../scripts/package-retention.cjs');

const projectRoot = path.resolve(__dirname, '..');
const hash = value => crypto.createHash('sha256').update(value).digest('hex');

function fixture(t) {
  const parent = path.join(projectRoot, '.test-data', 'public-package');
  fs.mkdirSync(parent, { recursive: true });
  assert.equal(fs.realpathSync(parent).toLowerCase(), parent.toLowerCase());
  const root = fs.mkdtempSync(path.join(parent, 'case-'));
  const output = path.join(root, 'dist', 'UFriend-0.1.38');
  const app = path.join(output, 'resources', 'app');
  fs.mkdirSync(path.join(app, 'app'), { recursive: true });
  fs.writeFileSync(path.join(output, '.ufriend-package-output'), 'Generated by scripts/package.cjs\n');
  fs.writeFileSync(path.join(output, 'UFriend.exe'), 'Synthetic package marker; never executed.');
  fs.writeFileSync(path.join(app, 'app', 'main.cjs'), '');
  fs.writeFileSync(path.join(app, 'package.json'), JSON.stringify({ name: 'ufriend', version: '0.1.38' }));
  const videoRuntime = copyMediaRuntimeSetup(output);
  const build = { product: 'UFriend', version: '0.1.38', builtAt: '2026-10-11T00:00:00Z', videoRuntime };
  fs.writeFileSync(path.join(output, 'BUILD-INFO.json'), JSON.stringify(build));
  const setup = path.join(output, 'resources', 'media-runtime-setup');
  t.after(() => {
    assert.equal(path.dirname(root), parent);
    assert.equal(fs.realpathSync(root).toLowerCase(), root.toLowerCase());
    fs.rmSync(root, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 });
  });
  return { root, output, setup, build, installer: path.join(setup, 'install-media-runtime.ps1'), destination: path.join(output, 'resources', 'ffmpeg') };
}

function upstreamFixture(f) {
  const source = path.join(f.root, 'upstream package [demo]');
  fs.mkdirSync(path.join(source, 'bin'), { recursive: true });
  const manifest = structuredClone(pinnedRuntime);
  for (const [name, upstream] of [['ffmpeg.exe', 'bin/ffmpeg.exe'], ['COPYING.GPLv3.txt', 'LICENSE'], ['UPSTREAM-README.txt', 'README.txt']]) {
    const content = Buffer.from('Synthetic ' + name + ': verified as data and never executed.\n');
    fs.writeFileSync(path.join(source, upstream), content);
    manifest.sha256[name] = hash(content);
    if (name !== 'ffmpeg.exe') fs.writeFileSync(path.join(f.setup, name), content);
  }
  fs.writeFileSync(path.join(f.setup, 'runtime.json'), JSON.stringify(manifest));
  f.build.videoRuntime.expectedSha256 = manifest.sha256['ffmpeg.exe'];
  fs.writeFileSync(path.join(f.output, 'BUILD-INFO.json'), JSON.stringify(f.build));
  return { source, manifest };
}

function runInstaller(f, args = []) {
  return spawnSync('powershell.exe', ['-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass', '-File', f.installer, ...args], {
    encoding: 'utf8', windowsHide: true, timeout: 20000, maxBuffer: 1024 * 1024,
  });
}
const windows = { skip: process.platform !== 'win32' };

test('public packaging rejects unknown flags and explicitly opts out of the media runtime', () => {
  assert.deepEqual(packagingOptions([]), { withoutFfmpeg: false });
  assert.deepEqual(packagingOptions(['--without-ffmpeg']), { withoutFfmpeg: true });
  assert.throws(() => packagingOptions(['--without-ffmepg']), /Usage/);
  assert.throws(() => packagingOptions(['--without-ffmpeg', '--without-ffmpeg']), /Usage/);
});

test('public setup contains pinned notices and installer but no executable, and retention recognizes the package', t => {
  const f = fixture(t);
  assert.equal(fs.existsSync(f.destination), false);
  assert.equal(fs.readdirSync(f.setup).some(name => /\.exe$/i.test(name)), false);
  assert.equal(f.build.videoRuntime.bundled, false);
  assert.equal(f.build.videoRuntime.expectedVersion, pinnedRuntime.version);
  for (const name of ['COPYING.GPLv3.txt', 'UPSTREAM-README.txt', 'SOURCES.md']) {
    assert.equal(hash(fs.readFileSync(path.join(f.setup, name))), pinnedRuntime.sha256[name]);
  }
  assert.equal(fs.existsSync(path.join(f.output, 'Install media runtime.cmd')), true);
  const packages = inspectPackages(path.dirname(f.output)).packages;
  assert.equal(packages.length, 1);
  assert.equal(packages[0].version, '0.1.38');
});

test('offline installation verifies and copies only required upstream files, then is idempotent', windows, t => {
  const f = fixture(t), { source, manifest } = upstreamFixture(f);
  fs.writeFileSync(path.join(source, 'unrelated.txt'), 'Must never enter the runtime.');
  const first = runInstaller(f, ['-From', source]);
  assert.equal(first.status, 0, first.stdout + first.stderr);
  assert.deepEqual(fs.readdirSync(f.destination).sort(), ['COPYING.GPLv3.txt', 'SOURCES.md', 'UPSTREAM-README.txt', 'ffmpeg.exe', 'runtime.json'].sort());
  for (const [name, expected] of Object.entries(manifest.sha256)) assert.equal(hash(fs.readFileSync(path.join(f.destination, name))), expected);
  const before = fs.statSync(path.join(f.destination, 'ffmpeg.exe')).mtimeMs;
  const second = runInstaller(f, ['-From', path.join(f.root, 'not-needed')]);
  assert.equal(second.status, 0, second.stdout + second.stderr);
  assert.match(second.stdout, /already installed/);
  assert.equal(fs.statSync(path.join(f.destination, 'ffmpeg.exe')).mtimeMs, before);
  assert.equal(fs.readdirSync(path.join(f.output, 'resources')).some(name => name.startsWith('.media-runtime-install-')), false);
});

test('an upstream binary hash mismatch leaves no published runtime and preserves the upstream files', windows, t => {
  const f = fixture(t), { source } = upstreamFixture(f);
  fs.writeFileSync(path.join(source, 'bin', 'ffmpeg.exe'), 'Changed synthetic file.');
  const result = runInstaller(f, ['-From', source]);
  assert.equal(result.status, 1, result.stdout + result.stderr);
  assert.match(result.stderr, /SHA-256 mismatch: ffmpeg.exe/);
  assert.equal(fs.existsSync(f.destination), false);
  assert.equal(fs.readFileSync(path.join(source, 'bin', 'ffmpeg.exe'), 'utf8'), 'Changed synthetic file.');
  assert.equal(fs.readdirSync(path.join(f.output, 'resources')).some(name => name.startsWith('.media-runtime-install-')), false);
});

test('an existing incomplete runtime is preserved rather than overwritten', windows, t => {
  const f = fixture(t), { source } = upstreamFixture(f);
  fs.mkdirSync(f.destination);
  fs.writeFileSync(path.join(f.destination, 'keep.txt'), 'Existing user file.');
  const result = runInstaller(f, ['-From', source]);
  assert.equal(result.status, 1, result.stdout + result.stderr);
  assert.equal(fs.readFileSync(path.join(f.destination, 'keep.txt'), 'utf8'), 'Existing user file.');
  assert.deepEqual(fs.readdirSync(f.destination), ['keep.txt']);
});

test('downloaded archive hash is checked before the extraction tool can run', windows, t => {
  const f = fixture(t);
  const installer = f.installer.replace(/'/g, "''");
  const command = `function Get-Command { param($Name, $CommandType, $ErrorAction) [pscustomobject]@{Source='must-not-be-executed.exe'} }; function Invoke-WebRequest { param($Uri, $OutFile, [switch]$UseBasicParsing) [IO.File]::WriteAllText($OutFile, 'Wrong archive fixture') }; & '${installer}'`;
  const result = spawnSync('powershell.exe', ['-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass', '-Command', command], { encoding: 'utf8', windowsHide: true, timeout: 20000 });
  assert.equal(result.status, 1, result.stdout + result.stderr);
  assert.match(result.stderr, /SHA-256 mismatch: ffmpeg.7z/);
  assert.doesNotMatch(result.stderr, /must-not-be-executed/);
  assert.equal(fs.existsSync(f.destination), false);
});
