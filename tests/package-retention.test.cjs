  const mismatch=packageFixture(f.dist,'UFriend-0.1.14','0.1.14');fs.writeFileSync(path.join(mismatch.path,'BUILD-INFO.json'),JSON.stringify({product:'UFriend',version:'0.1.13',builtAt:later}));
  const folderMismatch=packageFixture(f.dist,'UFriend-0.1.15','0.1.14');
